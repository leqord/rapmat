def serialize_phonons(phonons: Phonopy) -> str:
    """Serialize a Phonopy object to a gzip -> base64.
    """
    import base64
    import gzip

    from phonopy.interface.phonopy_yaml import PhonopyYaml

    py = PhonopyYaml(settings={"force_constants": False})
    py.set_phonon_info(phonons)
    raw = str(py).encode("utf-8")
    return base64.b64encode(gzip.compress(raw)).decode("ascii")


def deserialize_phonons(blob: str) -> Phonopy:
    """Reconstruct a Phonopy object from a string.
    """
    import base64
    import gzip
    import os
    import tempfile

    import phonopy

    text = gzip.decompress(base64.b64decode(blob)).decode("utf-8")
    tmp = tempfile.NamedTemporaryFile(
        "w", suffix=".phonopy.yaml", delete=False, encoding="utf-8"
    )
    try:
        tmp.write(text)
        tmp.close()

        return phonopy.load(tmp.name, produce_fc=True)
    finally:
        os.unlink(tmp.name)


def save_phonon_dispersion(phonons: Phonopy, save_path) -> None:
    """Render and save a phonon dispersion plot."""
    import warnings

    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        fig = phonons.auto_band_structure(plot=True)
    fig.savefig(str(save_path), dpi=150)
    plt.close(fig)
